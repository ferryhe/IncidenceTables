export function catalogLabel(field, value, language) {
  if (language !== ZH) return value;
  if (field === 'nation') return localizedRegion(value);
  const labels = chineseLabels[field];
  return labels && Object.hasOwn(labels, value) ? labels[value] : value;
}

export function matchingLabel(count, language) {
  const text = messages[language];
  return count === 1 ? text.matchingTable : text.matchingTablePlural;
}
